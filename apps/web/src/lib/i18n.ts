export type TranslationKey = keyof (typeof dictionaries)['id-ID'];

export function createTranslator(locale: Locale) {
  return (key: TranslationKey): string => dictionaries[locale][key];
}

export function detectLocale(): Locale {
  const stored = localStorage.getItem('live-voice-locale');
  if (stored === 'en-US' || stored === 'id-ID') return stored;
  return navigator.language.toLowerCase().startsWith('id') ? 'id-ID' : 'en-US';
}
